import assert from 'node:assert/strict';
import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
const { chromium, devices } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const output=resolve('TestResults/village-browser/navigation-touch');await mkdir(output,{recursive:true});
const browser=await chromium.launch({headless:true,executablePath:process.env.BROWSER_EXECUTABLE});
const context=await browser.newContext({...devices['iPhone 13'],deviceScaleFactor:1});
const page=await context.newPage(), checks=[], errors=[];
page.on('pageerror',error=>errors.push(error.message));
await page.route('http://navigation-touch.test/**',async route=>{
 const path=new URL(route.request().url()).pathname;
 if(path==='/sidebar.js')return route.fulfill({contentType:'text/javascript',body:await readFile(resolve(import.meta.dirname,'../../Client/Components/Sidebar/Sidebar.razor.js'))});
 assert.equal(path,'/');
 await route.fulfill({contentType:'text/html',body:'<meta name="viewport" content="width=device-width,initial-scale=1"><style>body{margin:0;min-height:100vh}canvas{display:block;width:320px;height:240px;touch-action:none}aside{position:fixed;inset:0 auto 0 0;width:100vw;transform:translateX(-100%);background:#182431}button{position:absolute;top:500px;left:0;width:44px;height:44px}</style><canvas></canvas><button class="sidebar-toggle">Menu</button><aside id="sidebar"></aside>'});
});
const record=name=>{checks.push(name);console.log(`PASS ${name}`);};
try{
 await page.goto('http://navigation-touch.test/');
 await page.evaluate(async()=>{const {init}=await import('/sidebar.js');window.opened=0;window.sidebarRuntime=init({invokeMethodAsync:async()=>window.opened++},'sidebar');});
 const cdp=await context.newCDPSession(page);
 const swipe=async(x1,y1,x2,y2)=>{
  await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x:x1,y:y1,id:1}]});
  for(let i=1;i<=4;i++)await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x:x1+(x2-x1)*i/4,y:y1+(y2-y1)*i/4,id:1}]});
  await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});await page.waitForTimeout(60);
 };
 const isOpen=()=>page.locator('aside').getAttribute('data-mobile-open');
 await swipe(5,350,150,350);assert.equal(await isOpen(),'true');
 assert.equal(await page.locator('.sidebar-toggle').getAttribute('aria-expanded'),'true');
 await swipe(385,350,220,350);assert.equal(await isOpen(),'false');
 record('Edge swipes open and close navigation and update its accessible state');
 await swipe(5,100,145,100);assert.equal(await isOpen(),'false');
 await swipe(5,520,145,520);assert.equal(await isOpen(),'false');
 record('Canvas and button gestures do not open the sidebar');
 await swipe(5,350,10,480);assert.equal(await isOpen(),'false');
 record('Vertical scrolling does not become a navigation gesture');
 await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x:5,y:350,id:1}]});
 await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x:125,y:350,id:1}]});
 assert.ok((await page.locator('aside').boundingBox()).x>-390);
 await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x:125,y:350,id:1},{x:200,y:400,id:2}]});
 await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
 assert.equal(await isOpen(),'false');
 assert.equal((await page.locator('aside').boundingBox()).x,-390);
 record('Adding a second finger cancels a partial sidebar drag');
 await page.setViewportSize({width:844,height:390});
 await swipe(5,350,205,350);assert.equal(await isOpen(),'true');
 assert.equal((await page.locator('aside').boundingBox()).width,844);
 await swipe(839,350,620,350);assert.equal(await isOpen(),'false');
 record('Sidebar gestures use the new viewport width after rotation');
 await page.evaluate(()=>window.sidebarRuntime.dispose());
 const count=await page.evaluate(()=>window.opened);
 await swipe(5,350,205,350);assert.equal(await isOpen(),'false');
 assert.equal(await page.evaluate(()=>window.opened),count);
 record('Disposal removes gesture listeners and callbacks');
 await page.evaluate(()=>{window.sidebarRuntime.toggleOpen();window.sidebarRuntime.setOpen(true);window.sidebarRuntime.clearInlineTransform();window.sidebarRuntime.dispose();});
 assert.equal(await isOpen(),'false');
 assert.equal(await page.evaluate(()=>window.opened),count);
 assert.equal(await page.evaluate(()=>window.sidebarRuntime.isOpen()),false);
 record('Late calls on a disposed sidebar stay inert and cleanup is idempotent');
 assert.equal(await page.evaluate(async()=>{const {init}=await import('/sidebar.js');return init({invokeMethodAsync:async()=>window.opened++},'already-removed');}),null);
 assert.equal(await page.evaluate(()=>typeof window.toggleSidebar),'undefined');
 record('Initialization after the sidebar element is removed registers no handlers');
 assert.deepEqual(errors,[]);
}finally{await writeFile(`${output}/results.json`,JSON.stringify({checks,errors},null,2));await browser.close();}
