import assert from 'node:assert/strict';
import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
const { chromium, devices } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const root=resolve(import.meta.dirname,'../../Client');
const output=resolve('TestResults/village-browser/tileset-touch');await mkdir(output,{recursive:true});
const browser=await chromium.launch({headless:true,executablePath:process.env.BROWSER_EXECUTABLE});
const context=await browser.newContext({...devices['iPhone 13'],deviceScaleFactor:1});
const page=await context.newPage(), checks=[], errors=[];
page.on('pageerror',error=>errors.push(error.message));
await page.route('http://villages-touch.test/**',async route=>{
 const path=new URL(route.request().url()).pathname;
 if(path==='/')return route.fulfill({contentType:'text/html',body:'<meta name="viewport" content="width=device-width,initial-scale=1"><style>body{margin:0;background:#17232b}canvas{width:320px;height:240px;display:block;touch-action:none}</style><canvas id="sheet"></canvas><input type="file" id="file">'});
 const file=path==='/editor.js'?`${root}/Components/Windows/Villages/TilesetDefinitionWindowComponent.razor.js`:path==='/atlas.png'?`${root}/wwwroot/media/villages/library-atlas.png`:path.startsWith('/ts/')?`${root}/wwwroot${path}`:null;
 assert.ok(file,`Unexpected fixture resource: ${path}`);
 let body=await readFile(file);if(path==='/editor.js')body=Buffer.from(body.toString().replaceAll('"../../../ts/','"/ts/'));
 await route.fulfill({contentType:path.endsWith('.png')?'image/png':'text/javascript',body});
});
const record=name=>{checks.push(name);console.log(`PASS ${name}`);};
try{
 await page.goto('http://villages-touch.test/');
 await page.evaluate(async()=>{
  const {init}=await import('/editor.js');window.selections=[];
  window.editor=init('sheet','file',{invokeMethodAsync:async(name,...args)=>{if(name==='OnSelectionChanged')window.selections.push(args);}},null);
  await window.editor.loadImageUrl('/atlas.png');window.editor.focusRegion(0,0,128,128);
 });
 const cdp=await context.newCDPSession(page);
 const touch=async(type,points)=>{await cdp.send('Input.dispatchTouchEvent',{type,touchPoints:points.map(([x,y,id])=>({x,y,id,radiusX:2,radiusY:2,force:1}))});await page.waitForTimeout(60);};
 await touch('touchStart',[[124,84,1]]);
 await touch('touchMove',[[172,108,1]]);
 await touch('touchEnd',[]);
 assert.deepEqual(await page.evaluate(()=>window.selections.at(-1)),[2,2,3,2,false]);
 record('A real touch drag selects every tile in a multi-tile rectangle');
 const before=await page.locator('canvas').screenshot();
 await touch('touchStart',[[100,100,1],[180,100,2]]);
 await touch('touchMove',[[70,100,1],[210,100,2]]);
 await touch('touchEnd',[]);
 assert.deepEqual(await page.evaluate(()=>window.selections.at(-1)),[2,2,3,2,false]);
 assert.notDeepEqual(await page.locator('canvas').screenshot(),before);
 record('Two-finger zoom changes the artwork scale without changing the selected object');
 const zoomed=await page.locator('canvas').screenshot();
 await touch('touchStart',[[80,100,1],[180,100,2]]);
 await touch('touchMove',[[115,120,1],[215,120,2]]);
 await touch('touchEnd',[]);
 assert.deepEqual(await page.evaluate(()=>window.selections.at(-1)),[2,2,3,2,false]);
 assert.notDeepEqual(await page.locator('canvas').screenshot(),zoomed);
 record('Two-finger panning retains the complete selection');
 await page.evaluate(()=>window.editor.focusRegion(0,0,128,128));
 await touch('touchStart',[[220,180,1]]);
 await touch('touchMove',[[350,270,1]]);
 await touch('touchEnd',[]);
 await touch('touchStart',[[148,60,1]]);await touch('touchEnd',[]);
 assert.deepEqual(await page.evaluate(()=>window.selections.at(-1)),[3,1,1,1,false]);
 record('Releasing outside the canvas does not leave the next touch stuck in a drag');
 await touch('touchStart',[[220,180,1]]);
 await touch('touchMove',[[244,204,1]]);
 await touch('touchCancel',[]);
 assert.deepEqual(await page.evaluate(()=>window.selections.at(-1)),[3,1,1,1,false]);
 record('An interrupted touch restores the previous selection');
 await page.mouse.move(100,156);await page.mouse.down();await page.mouse.move(148,180,{steps:3});await page.mouse.up();
 assert.deepEqual(await page.evaluate(()=>window.selections.at(-1)),[1,5,3,2,false]);
 record('Mouse dragging still selects the complete rectangle through pointer capture');
 await page.screenshot({path:`${output}/touch-selection.png`});
 await page.evaluate(()=>window.editor.dispose());
 assert.deepEqual(errors,[]);
}finally{await writeFile(`${output}/results.json`,JSON.stringify({checks,errors},null,2));await browser.close();}
